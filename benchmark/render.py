"""
benchmark/render.py - turn benchmarks/latest.json into (a) docs/reports/benchmark_report.md and (b) the block between the
BENCHMARK markers in README.md. Every number quoted in either file is produced here from the JSON, never typed by hand;
tests/test_benchmark.py fails if the files drift from the JSON.
"""

from __future__ import annotations

from typing import Any, Dict, List

from benchmark.plots import NAMES

START, END = "<!-- BENCHMARK:START (generated by python -m benchmark.run_all; do not edit by hand) -->", "<!-- BENCHMARK:END -->"
HOP_LABEL = {"cyber_rules": "Cyber Agent rules", "cyber_model": "Cyber model (NO_MODEL stub)", "physical_rules": "Physical Agent rules",
             "physical_model": "Physical model (assess; includes window refresh)", "orchestrator": "Orchestrator fusion",
             "trace_build": "Packet-trace build", "branches": "Both branches (concurrent, wall time)", "total": "TOTAL per command"}


def _pct(v: Any) -> str:
    return "n/a" if v is None else f"{100 * v:.1f}%"


def _num(v: Any, d: int = 3) -> str:
    return "n/a" if v is None else f"{v:.{d}f}"


def glance_rows(res: Dict[str, Any]) -> List[List[str]]:
    rows = []
    s = res["swat"]
    f = lambda c: [str(c["n"] if "n" in c else c["tp"] + c["fp"] + c["fn"] + c["tn"]), _num(c.get("accuracy")), _num(c.get("precision")), _num(c.get("recall")),
                   _num(c.get("f1")), _num(c.get("false_positive_rate")), f"{c['tn']:,} / {c['fp']:,} / {c['fn']:,} / {c['tp']:,}"]
    if s.get("status") == "OK":
        rows.append(["Physical model flag -> ALERT", "REAL SWaT held-out windows"] + f(s["advisory_model_flag"]))
    rc = res["rules"]["confusion"]
    rows.append(["Rule layers, all violations vs legitimate commands", "constructed commands"] + f(rc["overall"]))
    rows.append(["  cyber layer only", "constructed commands"] + f(rc["per_layer"]["cyber"]))
    rows.append(["  physical layer only", "constructed commands"] + f(rc["per_layer"]["physical"]))
    rows.append(["Rule layers, attack sessions vs benign sessions (incl. stealthy freeze/ramp)", "constructed sessions"] + f(res["attacker_plans"]["run_level_confusion"]))
    return rows


def glance_md(res: Dict[str, Any], figure_prefix: str) -> List[str]:
    L = ["| What is scored | Evidence | n | Accuracy | Precision | Recall | F1 | False-positive rate | TN / FP / FN / TP |", "|---|---|---|---|---|---|---|---|---|"]
    L += ["| " + " | ".join(r) + " |" for r in glance_rows(res)]
    rc = res["rules"]["confusion"]["three_class"]
    L += ["", "Three-class decision matrix of the rule layers on constructed commands (rows = truth, columns = decision):", "",
          "| truth | PASS | ALERT | DROP |", "|---|---|---|---|"]
    for k, v in rc.items():
        L.append(f"| {k} | {v['PASS']:,} | {v['ALERT']:,} | {v['DROP']:,} |")
    L += ["", f"![Whole-middleware confusion matrices]({figure_prefix}{NAMES['middleware']})", "",
          "**How to read this.** There is no single accuracy for the whole middleware, because the evidence has different strengths and must not be pooled. "
          "Only the first row is real-data performance (physical model, advisory, SWaT held-out). The other rows test the deterministic RULE layers on scenarios *we built*: "
          "perfect scores there mean each rule fires on what it was written for (a regression check), and the session-level row shows the honest gap, the stealthy "
          "in-bounds attacks the rules do not stop. Accuracy alone is misleading on imbalanced data: judge by recall, precision and the false-positive rate."]
    return L


def latency_md(res: Dict[str, Any]) -> List[str]:
    lat, env = res["latency"], res["environment"]
    c = lat["config"]
    L = [f"**What this is.** {lat['label']} {c['commands_per_repeat']} commands x {c['repeats']} repeats after {c['warmup']} warm-up, seed {c['seed']}; "
         f"{c['mix']}.", "",
         f"Measured on {env['platform']}, Python {env['python']}, {env['cpu_count']} CPUs, scikit-learn {env['scikit_learn']}, commit `{env['git_commit']}`. "
         "Latency depends on the machine: re-run `python -m benchmark.run_all` on yours.", "",
         "| Hop | mean (ms) | p50 (ms) | p95 (ms) | p99 (ms) |", "|---|---|---|---|---|"]
    for h, s in lat["hops"].items():
        L.append(f"| {HOP_LABEL.get(h, h)} | {_num(s['mean_ms'], 4)} | {_num(s['p50_ms'], 4)} | {_num(s['p95_ms'], 4)} | {_num(s['p99_ms'], 4)} |")
    t = lat["hops"]["total"]
    L += ["", f"![Per-hop latency](figures/{NAMES['latency']})"]
    L += ["", f"Spread of the total across repeats: mean {t['mean_ms_min_max_over_repeats'][0]}-{t['mean_ms_min_max_over_repeats'][1]} ms, "
          f"p95 {t['p95_ms_min_max_over_repeats'][0]}-{t['p95_ms_min_max_over_repeats'][1]} ms. The two branches overlap, so hops do not sum to the total."]
    live = lat.get("live_modbus_round_trip")
    if live and live.get("status") == "OK":
        rt = live["round_trip"]
        L += ["", f"Live Modbus round trip of a signed write to a running middleware ({live['writes']} writes): mean {rt['mean_ms']} ms, p95 {rt['p95_ms']} ms, p99 {rt['p99_ms']} ms."]
    elif live:
        L += ["", f"Live Modbus round trip: {live['status']}."]
    return L


def rules_md(res: Dict[str, Any]) -> List[str]:
    r, a = res["rules"], res["attacker_plans"]
    L = [f"**{r['label']}.** {r['per_case']} randomised scenarios per case, seed {r['seed']}, virtual clock. A scenario counts as detected only "
         "when the real pipeline returns DROP **with the expected reason**. The rules are deterministic, so 100 % is expected: this is a regression check "
         "that each rule fires on what it was written for, not evidence of performance against an unknown attacker.", "",
         "| Layer | Case | Expected | As expected |", "|---|---|---|---|"]
    for c in r["cases"]:
        L.append(f"| {c['layer']} | {c['case']} | `{c['expected']}` | {c['as_expected']}/{c['n']} ({_pct(c['rate'])}) |")
    L += ["", f"![Rule-based checks](figures/{NAMES['rules']})"]
    L += ["", f"Legitimate-command false-positive rate: **{_pct(r['legitimate_false_positive_rate'])}**. Violating scenarios detected with the expected reason: "
          f"**{r['violating_detected_with_expected_reason']}/{r['violating_scenarios']}**.", "",
          f"**Randomised attacker plans through the rule agents** ({a['label']}). {a['runs_per_type']} runs per type, seed {a['seed']}.", "",
          "| Attack type | Origin | Runs with at least one DROP | Drop reasons (frames) |", "|---|---|---|---|"]
    for t, v in a["types"].items():
        reasons = ", ".join(f"{k} {n}" for k, n in v["drop_reasons"].items()) or "none"
        L.append(f"| {t} | {v['origin']} | {v['runs_with_a_drop']}/{v['runs']} ({_pct(v['run_drop_rate'])}) | {reasons} |")
    L += ["", f"![Attacker plans through the rules](figures/{NAMES['plans']})"]
    L += ["", "The stealthy SWaT-derived behaviours (`freeze`, `ramp`) are mostly in-bounds and slow, so the rules alone do not stop them "
          "(a frozen value re-sent within 2 s is caught only by the duplicate-payload replay check). They are what the advisory physical model is for."]
    return L


def twin_md(res: Dict[str, Any]) -> List[str]:
    t = res["twin"]
    n = t["nominal"]
    L = [f"**{t['label']}.** Promoted physical model on the calibrated twin: {n['simulated_hours']} simulated hours of nominal operation with sensor noise.", "",
         f"* learned-model alarm episodes on the HEALTHY twin: **{n['model_alarm_episodes_per_hour']} per hour** ({n['model_flag_seconds']} flagged seconds)",
         f"* measured-envelope rule alarm episodes: **{n['envelope_alarm_episodes_per_hour']} per hour**", "",
         "| Synthetic actuator attack | first model flag (s after) | first envelope violation (s after) |", "|---|---|---|"]
    for name, s in t["scenarios"].items():
        L.append(f"| {name} | {s['first_model_flag_after_s']} | {s['first_envelope_violation_after_s']} |")
    L += ["", f"![Twin detection latency](figures/{NAMES['twin']})"]
    L += ["", "This measures the demonstration plant only. It says nothing about SWaT detection performance."]
    return L


def swat_md(res: Dict[str, Any]) -> List[str]:
    s = res["swat"]
    if s.get("status") != "OK":
        return [f"**NOT RUN.** {s.get('status', '')} SWaT lives only on the machine that has the archive: run "
                "`python -m benchmark.run_all --data-dir <archive>` there (or `python -m benchmark.swat_accuracy --data-dir <archive> --out benchmarks/swat_accuracy.json` "
                "and commit the JSON). No SWaT number is quoted until it has been measured."]
    f = s["advisory_model_flag"]
    seg = s["segments"]
    L = [f"**{s['label']}.** {s['protocol_note']}.", "",
         *([f"_Source: {s['provenance']}_", ""] if s.get("provenance") else []),
         f"Test block: {s['windows']:,} windows (stride {s['stride_s']} s): {s['attack_windows']:,} attack, {s['benign_windows']:,} benign ({s['benign_hours']} benign hours). "
         f"Operating point: Isolation Forest threshold {_num(s['operating_point']['isolation_forest_threshold'], 4)}, classifier threshold {_num(s['operating_point']['classifier_threshold'], 3)}, variant `{s['operating_point']['variant']}`.", "",
         "| Decision rule | precision | recall | F1 | false-positive rate | accuracy | balanced accuracy | alarm episodes / benign hour |", "|---|---|---|---|---|---|---|---|"]
    for key, label in (("advisory_model_flag", "Advisory model flag (drives ALERT)"), ("envelope_rule_alone (alert-only)", "Envelope rule alone (alert-only)"),
                       ("model_flag_or_envelope", "Model flag or envelope")):
        c = s[key]
        L.append(f"| {label} | {_num(c['precision'])} | {_num(c['recall'])} | {_num(c['f1'])} | {_num(c['false_positive_rate'])} | {_num(c.get('accuracy'))} | {_num(c.get('balanced_accuracy'))} | {c.get('alarm_episodes_per_benign_hour')} |")
    base = f["always_benign_baseline_accuracy"]
    L += ["", f"Plain accuracy is shown but is **not the headline**: attacks are only {100 * (1 - base):.1f}% of windows, so a system that never flags anything "
          f"would score **{_num(base)}** accuracy (balanced accuracy 0.5). Judge the model by recall, precision, false alarms per hour and AUC."]
    L += ["", "Confusion counts (windows; rows = true label, columns = prediction):", "",
          "| Decision rule | benign, no flag (TN) | benign, flagged (FP) | attack, no flag (FN) | attack, flagged (TP) |", "|---|---|---|---|---|"]
    for key, label in (("advisory_model_flag", "Advisory model flag"), ("envelope_rule_alone (alert-only)", "Envelope rule alone"),
                       ("model_flag_or_envelope", "Model flag or envelope")):
        c = s[key]
        L.append(f"| {label} | {c['tn']:,} | {c['fp']:,} | {c['fn']:,} | {c['tp']:,} |")
    L += ["", f"![Confusion matrices on the held-out SWaT test block](figures/{NAMES['confusion']})"]
    L += ["", f"ROC-AUC (attack probability) **{_num(s.get('roc_auc_attack_probability'))}**, ROC-AUC (Isolation Forest score) {_num(s.get('roc_auc_isolation_forest_score'))}, "
          f"average precision {_num(s.get('average_precision_attack_probability'))}.",
          f"Attack segments detected: **{seg['detected']}/{seg['total']}**; median detection latency {_num(seg['median_detection_latency_s'], 1)} s "
          "(first flagged attack window after the segment starts).", ""]
    ex = s.get("excluding_largest_segment")
    if ex:
        c = ex["advisory_model_flag"]
        L.append(f"Excluding the largest segment ({ex['segment']}, {_pct(ex['share_of_attack_windows'])} of attack windows): precision {_num(c['precision'])}, recall {_num(c['recall'])}, F1 {_num(c['f1'])}.")
        L.append("")
    if not seg.get("per_segment"):
        return L + ["The per-segment table is not part of this record (it was taken from the printed console summary); "
                    "re-run `python -m benchmark.swat_accuracy ... --out benchmarks/swat_accuracy.json` to include it."]
    L += [f"![Per-segment detection](figures/{NAMES['segments']})", "",
          "| Segment | attack windows | duration (s) | flagged windows | detected | latency (s) |", "|---|---|---|---|---|---|"]
    for g in seg["per_segment"]:
        L.append(f"| {g['segment']} | {g['attack_windows']} | {g['duration_s']:.0f} | {g['flagged_windows']} | {'yes' if g['detected'] else 'no'} | {_num(g['detection_latency_s'], 0)} |")
    return L


def render_markdown(res: Dict[str, Any]) -> str:
    env = res["environment"]
    L = ["# IndustrialMind benchmark report", "",
         f"_Generated {env['generated_utc']} UTC by `python -m benchmark.run_all` at commit `{env['git_commit']}`. Every number below comes from "
         "`benchmarks/latest.json`; nothing is typed by hand._", "",
         "Four sections, deliberately separate because they answer different questions and have different evidential weight:", "",
         "| Section | Data | What it supports |", "|---|---|---|",
         "| 1. Latency | constructed workload, real code | speed of the decision pipeline |",
         "| 2. Held-out SWaT | REAL data (test block) | the only real-data detection performance (physical side) |",
         "| 3. Rule-based checks | constructed scenarios | each deterministic rule fires on what it was written for |",
         "| 4. Twin measurements | synthetic plant | demo behaviour of the model on the digital twin |", "",
         "## Whole middleware at a glance", ""] + glance_md(res, "figures/") + ["", "## 1. Latency (per hop)", ""] + latency_md(res) + ["", "## 2. Held-out SWaT (real data)", ""] + swat_md(res) + \
        ["", "## 3. Rule-based checks and constructed scenarios (NOT SWaT, NOT a learned model)", ""] + rules_md(res) + \
        ["", "## 4. Digital-twin measurements (synthetic plant, NOT SWaT)", ""] + twin_md(res) + \
        ["", "## Known limitations", "",
         "* The cyber layer cannot be evaluated on SWaT (no signatures, replay tags or source addresses in the archive): Section 3 is rule testing.",
         "* The cyber branch has no learned model by design (a SWaT-trained candidate was weak and was not promoted); the physical model is advisory.",
         "* A learned fusion model was tried and rejected (test AUC below the physical model alone): `docs/reports/fusion_training_report_swat.md`.",
         "* The SWaT test block was also seen in physical training run 2 (disclosed protocol revision): held-out, not a pristine blind test.",
         "* SWaT has no network-layer attacks: flood, replay and impossible-command are synthetic extensions; freeze, ramp and cross-register follow SWaT behaviours.",
         "* Latency is in-process decision latency on the machine named above, not network latency."]
    return "\n".join(L) + "\n"


def render_readme_block(res: Dict[str, Any]) -> str:
    env = res["environment"]
    s, lat, r = res["swat"], res["latency"], res["rules"]
    t = lat["hops"]["total"]
    L = [START, "", f"_Regenerate: `python -m benchmark.run_all [--data-dir <SWaT archive>]`. Full tables: `docs/reports/benchmark_report.md`. "
         f"These numbers: {env['platform']}, Python {env['python']}, commit `{env['git_commit']}`._", "",
         f"* **Decision latency** (real pipeline, in-process, {lat['config']['commands_per_repeat']} commands x {lat['config']['repeats']}): "
         f"mean **{_num(t['mean_ms'], 3)} ms**, p95 **{_num(t['p95_ms'], 3)} ms**, p99 **{_num(t['p99_ms'], 3)} ms** per command (not network latency)."]
    live = lat.get("live_modbus_round_trip")
    if live and live.get("status") == "OK":
        L[-1] += (f" Live Modbus round trip of a signed write to a running middleware (client side, {live['writes']} writes): "
                  f"mean {live['round_trip']['mean_ms']} ms, p95 {live['round_trip']['p95_ms']} ms.")
    if s.get("status") == "OK":
        f = s["advisory_model_flag"]
        L.append(f"* **Held-out SWaT test block** (real data, physical model only, advisory): ROC-AUC **{_num(s.get('roc_auc_attack_probability'), 2)}**, "
                 f"precision {_num(f['precision'], 2)}, recall {_num(f['recall'], 2)}, F1 {_num(f['f1'], 2)}, "
                 f"{f['alarm_episodes_per_benign_hour']} false-alarm episodes per hour, "
                 f"{s['segments']['detected']}/{s['segments']['total']} attack segments detected.")
    else:
        L.append("* **Held-out SWaT test block:** NOT RUN on this machine (the data lives only where the archive is). No SWaT number is quoted until measured.")
    L += [f"* **Rule-based checks** (constructed scenarios, not SWaT): {r['violating_detected_with_expected_reason']}/{r['violating_scenarios']} violating scenarios "
          f"dropped with the expected reason, legitimate false-positive rate {_pct(r['legitimate_false_positive_rate'])}. Deterministic rules: a regression check, not a detection claim.",
          f"* **Twin** (synthetic plant, not SWaT): {res['twin']['nominal']['model_alarm_episodes_per_hour']} model alarm episodes per hour on the healthy twin.", ""]
    L += ["", "**Whole middleware at a glance** (details and the 3-class matrix in the report):", ""] + glance_md(res, "docs/reports/figures/")[:2 + len(glance_rows(res))] + [""]
    L.append(f"![Whole-middleware confusion matrices](docs/reports/figures/{NAMES['middleware']})")
    L.append("")
    if s.get("status") == "OK":
        L.append(f"![Held-out SWaT confusion matrices](docs/reports/figures/{NAMES['confusion']})")
        L.append("")
    L += [f"![Per-hop latency](docs/reports/figures/{NAMES['latency']})", "", END]
    return "\n".join(L)


def update_readme(readme_text: str, block: str) -> str:
    if START in readme_text and END in readme_text:
        a, b = readme_text.index(START), readme_text.index(END) + len(END)
        return readme_text[:a] + block + readme_text[b:]
    raise ValueError("README.md has no BENCHMARK markers")
